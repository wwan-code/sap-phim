import { createSlice, createSelector, createEntityAdapter } from "@reduxjs/toolkit";

const MAX_RECENT_NOTIFICATIONS = 50;


const notificationsAdapter = createEntityAdapter({
  selectId: (notification) => notification.id,
  sortComparer: (a, b) => {
    const dateA = new Date(a.created_at || 0).getTime();
    const dateB = new Date(b.created_at || 0).getTime();
    return dateB - dateA;
  },
});

const initialState = notificationsAdapter.getInitialState({
  unreadCount: 0,
  lastNotification: null,
});

export const notificationSlice = createSlice({
  name: "notification",
  initialState,
  reducers: {
    /**
     * Set unread count (from server)
     */
    setUnreadCount: (state, action) => {
      state.unreadCount = Math.max(0, action.payload);
    },

    /**
     * Increment unread count (on new notification)
     */
    incrementUnread: (state) => {
      state.unreadCount += 1;
    },

    /**
     * Decrement unread count (on mark as read)
     */
    decrementUnread: (state) => {
      state.unreadCount = Math.max(0, state.unreadCount - 1);
    },

    /**
     * Reset unread count to 0 (on mark all as read)
     */
    resetUnread: (state) => {
      state.unreadCount = 0;
    },

    /**
     * Add a new notification from Socket.IO push
     */
    addNotification: (state, action) => {
      const notification = action.payload;
      if (!notification?.id) return;

      // Add to normalized entities
      notificationsAdapter.addOne(state, notification);
      state.lastNotification = notification;

      // Enforce limit
      if (state.ids.length > MAX_RECENT_NOTIFICATIONS) {
        const lastId = state.ids[state.ids.length - 1];
        notificationsAdapter.removeOne(state, lastId);
      }
    },

    /**
     * Mark a notification as read
     */
    markNotificationRead: (state, action) => {
      const id = action.payload;
      if (!id) return;

      notificationsAdapter.updateOne(state, {
        id,
        changes: {
          is_read: true,
          read_at: new Date().toISOString()
        }
      });
    },

    /**
     * Mark all notifications as read
     */
    markAllNotificationsRead: (state) => {
      const updates = state.ids.map(id => ({
        id,
        changes: {
          is_read: true,
          read_at: new Date().toISOString()
        }
      }));
      notificationsAdapter.updateMany(state, updates);
    },

    /**
     * Remove a notification
     */
    removeNotification: (state, action) => {
      notificationsAdapter.removeOne(state, action.payload);
    },

    /**
     * Clear all notifications
     */
    clearNotifications: (state) => {
      notificationsAdapter.removeAll(state);
      state.unreadCount = 0;
      state.lastNotification = null;
    },

    /**
     * Clear last notification (after toast is shown)
     */
    clearLastNotification: (state) => {
      state.lastNotification = null;
    },

    /**
     * Reset on logout
     */
    resetNotificationState: (state) => {
      notificationsAdapter.removeAll(state);
      state.unreadCount = 0;
      state.lastNotification = null;
    },
  },
});

export const {
  setUnreadCount,
  incrementUnread,
  decrementUnread,
  resetUnread,
  addNotification,
  markNotificationRead,
  markAllNotificationsRead,
  removeNotification,
  clearNotifications,
  clearLastNotification,
  resetNotificationState,
} = notificationSlice.actions;

// ========================================
// SELECTORS
// ========================================

const selectNotificationState = (state) => state.notification;

// Base selectors generated by the adapter
const adapterSelectors = notificationsAdapter.getSelectors(selectNotificationState);

export const selectUnreadCount = createSelector(
  [selectNotificationState],
  (notification) => notification.unreadCount,
);

export const selectHasUnread = createSelector(
  [selectUnreadCount],
  (count) => count > 0,
);

export const selectRecentNotifications = adapterSelectors.selectAll;

export const selectLastNotification = createSelector(
  [selectNotificationState],
  (notification) => notification.lastNotification,
);

export default notificationSlice.reducer;
